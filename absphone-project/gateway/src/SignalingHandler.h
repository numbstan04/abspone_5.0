#pragma once

#include "ISignalingHandler.h"
#include "CallSession.h"
#include <string>
#include <memory>
#include <atomic>
#include <thread>
#include <mutex>
#include <functional>
#include <cstdint>

namespace vcs { namespace gateway {

// Forward declarations
class SessionManager;

/**
 * @brief Signaling Handler Base Class
 *
 * Provides base implementation for signaling handlers. Subclasses implement
 * the protocol stack interactions only.
 *
 * Design Principles (docs/07 会话层施工图):
 * 1. Session storage is unified in the injected SessionManager (single source
 *    of truth); the handler keeps NO session maps of its own.
 * 2. SessionId is generated by SessionManager; the handler only binds the
 *    protocol-stack callId via SM->AddSession.
 * 3. Final teardown goes through SessionManager::MarkTerminated — that is the
 *    single publish point for CallTerminated. The handler-level Notify*
 *    callbacks stay for adapter-internal bookkeeping only.
 * 4. Interacts with upper layer through ISignalingHandlerCallback.
 */
class SignalingHandler : public ISignalingHandler {
public:
    /**
     * @brief Constructor
     * @param protocol protocol name ("SIP" / "H.323" / "WebRTC")
     * @param localUri local URI
     * @param sessionManager session manager pointer (nullptr = injected later
     *                       via SetSessionManager)
     */
    SignalingHandler(const std::string& protocol,
                     const std::string& localUri,
                     SessionManager* sessionManager = nullptr);
    virtual ~SignalingHandler() override;

    // ============================================================
    // ISignalingHandler Implementation
    // ============================================================

    bool Start() override;
    void Stop() override;

    CallSession* GetSession(int callId) override;
    CallSession* GetSessionById(const std::string& sessionId) override;
    void UpdateSessionState(int callId, SessionState state) override;
    void SetSessionMediaTransport(int callId, std::shared_ptr<IRtpTransport> transport) override;
    std::shared_ptr<IRtpTransport> GetSessionMediaTransport(int callId) override;
    std::vector<int> GetActiveCallIds() const override;
    size_t GetActiveSessionCount() const override;

    vcs::Response InitiateCall(const std::string& callee,
                                const Params& params,
                                std::string& sessionId) override;
    vcs::Response AcceptCall(int callId, const Params& params) override;
    vcs::Response RejectCall(int callId, const std::string& reason) override;
    vcs::Response TerminateCall(int callId, const std::string& reason) override;

    // ============================================================
    // Dependency Injection
    // ============================================================

    /**
     * @brief Inject SessionManager (must be set before Start)
     */
    void SetSessionManager(SessionManager* sessionManager);

    /**
     * @brief Get the currently injected SessionManager
     */
    SessionManager* GetSessionManager() const { return sessionManager_; }

    // ============================================================
    // Callback Settings (optional lambda versions)
    // ============================================================

    void SetCallback(ISignalingHandlerCallback* callback);

    void SetCallIncomingCallback(std::function<void(int, const std::string&, const Params&)> callback);
    void SetCallStateChangedCallback(std::function<void(int, SessionState)> callback);
    void SetCallConnectedCallback(std::function<void(int)> callback);
    void SetCallTerminatedCallback(std::function<void(int, const std::string&)> callback);
    void SetSignalingErrorCallback(std::function<void(int, int, const std::string&)> callback);

    // Media ready callback with codec info
    void SetMediaReadyCallback(std::function<void(int, const std::string&, std::shared_ptr<IRtpTransport>)> callback);

    struct MediaReadyInfo {
        int callId = 0;
        std::string remoteAddress;
        int remotePort = 0;
        std::shared_ptr<IRtpTransport> transport;
        std::string audioCodecName;
        uint8_t audioPayloadType = 0;
        std::string videoCodecName;
        uint8_t videoPayloadType = 0;
        bool hasSecondaryVideo = false;
        std::string secondaryVideoCodecName;
        uint8_t secondaryVideoPayloadType = 0;
    };
    void SetMediaReadyCallbackEx(std::function<void(const MediaReadyInfo&)> callback);

    // ============================================================
    // Local Media Configuration (for external SDP generation)
    // ============================================================

    /// Set local media address (for external SDP generation)
    virtual void SetLocalMediaAddress(const std::string& address) {}

    /// Set local media ports (for external SDP generation)
    virtual void SetLocalMediaPorts(uint16_t audioPort, uint16_t videoPort) {}

    // ============================================================
    // Background Cleanup Configuration
    // ============================================================

    /**
     * @brief Set the interval at which the background cleanup thread runs.
     *        Timeout policy itself lives in SessionManager (docs/07 §2.5).
     */
    void SetCleanupInterval(uint32_t intervalSeconds);

    /// @return Current cleanup interval in seconds.
    uint32_t GetCleanupInterval() const { return cleanupIntervalSeconds_; }

    /**
     * @brief Start the background cleanup thread (auto-started by Start()).
     */
    bool StartCleanupThread();

    /**
     * @brief Stop the background cleanup thread.
     */
    void StopCleanupThread();

    /// @return true if the cleanup thread is currently running.
    bool IsCleanupThreadRunning() const { return cleanupThreadRunning_.load(); }

protected:
    // ============================================================
    // Methods that subclasses can override
    // ============================================================

    /// Execute start logic
    virtual bool DoStart() { return true; }

    /// Execute stop logic
    virtual void DoStop() {}

    /// Send signaling message to remote
    virtual bool DoSendSignaling(const std::string& msg) { return true; }

    /// Actually initiate call (subclass implementation)
    /// @return callId (>= 0) on success; -1 on failure. Never return 0 to mean
    ///         failure: 0 is a legitimate protocol-stack call ID.
    virtual int DoInitiateCall(const std::string& callee, const Params& params) { return -1; }

    /// Actually accept call (subclass implementation)
    virtual bool DoAcceptCall(int callId, const Params& params) { return true; }

    /// Actually reject call (subclass implementation)
    virtual bool DoRejectCall(int callId, const std::string& reason) { return true; }

    /// Actually terminate call (subclass implementation)
    virtual bool DoTerminateCall(int callId, const std::string& reason) { return true; }

    // ============================================================
    // Internal methods (called by subclasses in protocol stack callbacks)
    // ============================================================

    /**
     * @brief Create a session in the injected SessionManager and bind callId.
     *
     * sessionId is generated by the SM ({proto}_{seq}); the handler only
     * stamps session->callId and registers the callId index.
     *
     * @param callId       Protocol-stack call ID (e.g. PJSIP).
     * @param caller       Caller URI.
     * @param confId       Target conference ID; empty = SM default ("local").
     * @param initialState IncomingPending for inbound, OutgoingPending for outbound.
     * @return raw session pointer (SM owns the shared_ptr); nullptr on failure.
     */
    CallSession* CreateSession(int callId,
                               const std::string& caller,
                               const std::string& confId = "",
                               SessionState initialState = SessionState::IncomingPending);

    /// Notify callback
    void NotifyCallIncoming(int callId, const std::string& caller, const Params& params);
    void NotifyCallStateChanged(int callId, SessionState state);
    void NotifyCallConnected(int callId);
    void NotifyCallTerminated(int callId, const std::string& reason);
    void NotifySignalingError(int callId, int errorCode, const std::string& errorMsg);
    void NotifyMediaReady(int callId, const std::string& remoteAddress, int remotePort);

    /// Media ready notification with codec info
    void NotifyMediaReadyEx(const MediaReadyInfo& info);

    /// Get protocol name
    const std::string& GetProtocol() const { return protocol_; }

    /// Get local URI
    const std::string& GetLocalUri() const { return localUri_; }

    /// ProtocolType derived from protocol_ name (for SM session tagging)
    ProtocolType GetProtocolType() const;

protected:
    /**
     * @brief Tear down a session and publish CallTerminated via SM (single
     *        publish point), then run the adapter-level Notify callbacks.
     *
     * @param callId Protocol-stack call ID
     * @param reason Termination reason
     * @return true if the session existed and was terminated now
     */
    bool TerminateSession(int callId, const std::string& reason, int cause = 0);

private:
    std::string protocol_;
    std::string localUri_;
    bool running_;

    ISignalingHandlerCallback* callback_;

    // SessionManager injection (non-owning pointer; lifetime owned by GatewayManager)
    SessionManager* sessionManager_ = nullptr;

    // Lambda callbacks
    std::function<void(int, const std::string&, const Params&)> callIncomingCallback_;
    std::function<void(int, SessionState)> callStateChangedCallback_;
    std::function<void(int)> callConnectedCallback_;
    std::function<void(int, const std::string&)> callTerminatedCallback_;
    std::function<void(int, int, const std::string&)> signalingErrorCallback_;
    std::function<void(int, const std::string&, std::shared_ptr<IRtpTransport>)> mediaReadyCallback_;

    // Extended media ready callback (with codec info)
    std::function<void(const MediaReadyInfo&)> mediaReadyCallbackEx_;

    // ============================================================
    // Background Cleanup Thread Members
    // ============================================================

    /// Cleanup cadence keeper (docs/07: cadence here, judgment in SM).
    std::thread cleanupThread_;

    /// Atomic flag controlling the lifetime of `cleanupThread_`.
    std::atomic<bool> cleanupThreadRunning_{false};

    /// How often the cleanup thread wakes up (seconds). Must be >= 1.
    uint32_t cleanupIntervalSeconds_ = 30;

    /// Worker function executed by `cleanupThread_`.
    void CleanupThreadFunc();
};

} // namespace gateway
} // namespace vcs
